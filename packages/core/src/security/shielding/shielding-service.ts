import {
  type ClientTier,
  RawMcpAccessForbiddenError,
  type CasePayloadInput,
  type IntakeAssessmentInput,
  type ConciergeMessageInput,
  type ShieldOptions,
} from './types.js';
import type { WhiteLabelBranding } from '../../tenant/types.js';
import { DEFAULT_PLATFORM_BRANDING } from '../../tenant/resolver.js';

export class ClientShieldingService {
  /**
   * Resolves the client security tier based on host, white-label resolution, and user role.
   */
  public static resolveClientTier(context: {
    host?: string | undefined;
    isWhiteLabel?: boolean | undefined;
    userRole?: string | undefined;
    tenantTier?: string | undefined;
  }): ClientTier {
    const staffRoles = ['super_admin', 'admin', 'case_manager', 'verifier', 'finance', 'staff'];
    if (context.userRole && staffRoles.includes(context.userRole)) {
      return 'internal_staff';
    }

    if (context.isWhiteLabel === true || context.tenantTier === 'tier2_partner_agency') {
      return 'b2b2c_partner';
    }

    if (context.host) {
      const cleanHost = context.host.toLowerCase().split(':')[0] || '';
      if (
        cleanHost !== 'visahobe.com' &&
        cleanHost !== 'localhost' &&
        cleanHost !== '127.0.0.1' &&
        (cleanHost.includes('visa.') || cleanHost.endsWith('.visahobe.com'))
      ) {
        return 'b2b2c_partner';
      }
    }

    return 'b2c_retail';
  }

  /**
   * Shields a visa case payload, stripping wholesale margins, agency branding (for retail),
   * internal caseworker notes, and raw agent confidence internals (ADR-012).
   */
  public static shieldCaseRecord(
    payload: CasePayloadInput,
    tier: ClientTier,
    options?: ShieldOptions,
  ): Record<string, unknown> {
    if (tier === 'internal_staff') {
      return { ...payload };
    }

    const shielded: Record<string, unknown> = { ...payload };

    // Strip sensitive internal casework notes across all non-staff tiers
    delete shielded['internalCaseworkNotes'];
    delete shielded['agentConfidenceScore'];
    delete shielded['agentAutonomyLevel'];
    delete shielded['agentAuditHash'];

    if (tier === 'b2c_retail') {
      // B2C Retail applicants must never see B2B partner agency identity, wholesale pricing, or margins
      delete shielded['wholesaleCost'];
      delete shielded['wholesaleDiscountPercentage'];
      delete shielded['agencyMarkup'];
      delete shielded['partnerAgencyId'];
      delete shielded['partnerAgencyName'];

      if (shielded['metadata'] && typeof shielded['metadata'] === 'object') {
        const meta = { ...(shielded['metadata'] as Record<string, unknown>) };
        delete meta['wholesale'];
        delete meta['discount'];
        delete meta['internalNotes'];
        delete meta['agentInternals'];
        delete meta['partnerAgencyId'];
        shielded['metadata'] = meta;
      }
    } else if (tier === 'b2b2c_partner') {
      // B2B2C Partner clients see their agency context, but platform wholesale base margins are hidden
      delete shielded['wholesaleCost'];
      delete shielded['wholesaleDiscountPercentage'];

      // Enforce tenant boundary safety
      if (
        options?.callerTenantId &&
        payload.tenantId &&
        payload.tenantId !== options.callerTenantId
      ) {
        delete shielded['partnerAgencyId'];
        delete shielded['partnerAgencyName'];
      }
    }

    return shielded;
  }

  /**
   * Shields an intake assessment result before serialization to the client surface.
   */
  public static shieldIntakeAssessment(
    assessment: IntakeAssessmentInput,
    tier: ClientTier,
  ): Record<string, unknown> {
    if (tier === 'internal_staff') {
      return { ...assessment };
    }

    const shielded: Record<string, unknown> = { ...assessment };

    delete shielded['wholesaleFee'];
    delete shielded['partnerAgencyDiscount'];
    delete shielded['internalConfidenceScore'];
    delete shielded['caseworkRoutingNotes'];

    if (tier === 'b2c_retail') {
      shielded['branding'] = DEFAULT_PLATFORM_BRANDING;
    }

    return shielded;
  }

  /**
   * Shields white-label branding parameters according to tier.
   */
  public static shieldBranding(
    branding: WhiteLabelBranding | undefined,
    tier: ClientTier,
  ): WhiteLabelBranding {
    if (tier === 'b2c_retail' || !branding) {
      return DEFAULT_PLATFORM_BRANDING;
    }
    return branding;
  }

  /**
   * Shields conversational messages generated by the AI concierge.
   */
  public static shieldConciergeMessage(
    message: ConciergeMessageInput,
    tier: ClientTier,
  ): ConciergeMessageInput {
    if (tier === 'internal_staff') {
      return { ...message };
    }

    const shieldedMeta = message.metadata ? { ...message.metadata } : undefined;
    if (shieldedMeta) {
      delete shieldedMeta['confidenceScore'];
      delete shieldedMeta['autonomyLevel'];
      delete shieldedMeta['internalCaseworkNotes'];
      delete shieldedMeta['wholesaleCost'];
    }

    return {
      role: message.role,
      content: message.content,
      metadata: shieldedMeta,
    };
  }

  /**
   * Asserts that a client tier is permitted to access raw MCP server endpoints (ADR-012 §3.3).
   * Throws RawMcpAccessForbiddenError if attempted by b2c_retail.
   */
  public static assertNoRawMcpAccess(tier: ClientTier): void {
    if (tier === 'b2c_retail') {
      throw new RawMcpAccessForbiddenError();
    }
  }
}
